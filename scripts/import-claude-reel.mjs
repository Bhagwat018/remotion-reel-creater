#!/usr/bin/env node
import fs from "fs";
import path from "path";
import { execSync } from "child_process";
import { fileURLToPath } from "url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, "..");

console.log("\n=======================================================");
console.log("🎬 Claude/Ootto to Remotion Reel Importer");
console.log("=======================================================\n");

const inputFile = path.join(rootDir, "claude_reel.json");

if (!fs.existsSync(inputFile)) {
  console.log(`ℹ️ Paste your Claude output into "claude_reel.json" in the project root.`);
  console.log(`Creating template at: ${inputFile} ...\n`);

  const template = {
    meta: {
      slug: "claude-viral-reel-1",
      topic: "Topic Generated by Claude & Ootto",
      title: "SHOCKING HOOK TITLE IN CAPS",
      handle: "@techwith.GenZ",
      voice: "rohan",
      voiceSpeed: 1.1,
      captions: true,
      instagramCaption: "Your viral caption with hashtags here..."
    },
    scenes: [
      {
        id: "s1-hook",
        type: "title",
        headline: "FIRST 3 SECONDS HOOK",
        leadIn: "BREAKING TRUTH 🚨",
        voice: "Yeh baat sunkar aapko shock lagega!",
        startSec: 0,
        endSec: 4.5
      },
      {
        id: "s2-evidence",
        type: "evidence",
        headline: "THE PROOF NOBODY TELLS YOU",
        leadIn: "SHOCKING PROOF 📊",
        voice: "Asli hisaab yahan dekho!",
        startSec: 4.5,
        endSec: 12.0
      },
      {
        id: "s3-cta",
        type: "cta",
        headline: "COMMENT 'REEL' FOR FULL DETAILS",
        leadIn: "DON'T MISS OUT 🔥",
        voice: "Save this reel and comment REEL for the direct link!",
        startSec: 12.0,
        endSec: 16.0
      }
    ]
  };

  fs.writeFileSync(inputFile, JSON.stringify(template, null, 2), "utf-8");
  console.log(`✅ Template created at "claude_reel.json". Paste your Claude response and run this command again!`);
  process.exit(0);
}

try {
  const content = fs.readFileSync(inputFile, "utf-8").trim();
  let reelData;

  // Extract JSON if wrapped in markdown code fence
  const jsonMatch = content.match(/```(?:json)?\s*([\s\S]*?)\s*```/);
  if (jsonMatch) {
    reelData = JSON.parse(jsonMatch[1]);
  } else {
    reelData = JSON.parse(content);
  }

  const slug = reelData.meta?.slug || `claude-reel-${Date.now()}`;
  const targetDir = path.join(rootDir, "reels", slug);
  fs.mkdirSync(targetDir, { recursive: true });

  const targetFile = path.join(targetDir, "reel.json");
  fs.writeFileSync(targetFile, JSON.stringify(reelData, null, 2), "utf-8");

  console.log(`✅ Reel imported successfully into: reels/${slug}/reel.json`);
  console.log(`\n🚀 To render this reel with Indian voice & motion graphics:`);
  console.log(`   npm run render:reel -- ${slug}\n`);
} catch (err) {
  console.error("❌ Error importing Claude reel:", err.message);
}

