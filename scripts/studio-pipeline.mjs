#!/usr/bin/env node
import { execSync, spawnSync } from "child_process";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import dotenv from "dotenv";

dotenv.config();

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, "..");
const historyPath = path.join(rootDir, "data", "competitors_history.json");

console.log("\n=======================================================");
console.log("🎬 10-15 MINUTE PROFESSIONAL TECH REEL PRODUCTION STUDIO");
console.log("   Channel: @techwith.GenZ | Standard: 30-35s High Retention");
console.log("   Visuals: Heavy Architecture Diagrams, Split Battles & Code");
console.log("   Audio:   Sarvam AI (Shubh) + Broadcast Studio EQ & -14 LUFS");
console.log("=======================================================\n");

const shouldPost = process.argv.includes("--post");
const typeArg = process.argv.find((a) => a.startsWith("--type="))?.split("=")[1];
const voiceArg = process.argv.find((a) => a.startsWith("--voice="))?.split("=")[1] || "shubh";
const explicitSlug = process.argv.find((a) => a.startsWith("--slug="))?.split("=")[1];
const explicitTopic = process.argv.find((a) => a.startsWith("--topic="))?.split("=")[1] ||
  (process.argv.indexOf("--topic") !== -1 ? process.argv[process.argv.indexOf("--topic") + 1] : null);
const explicitUrl = process.argv.find((a) => a.startsWith("--url="))?.split("=")[1] ||
  (process.argv.indexOf("--url") !== -1 ? process.argv[process.argv.indexOf("--url") + 1] : null);

async function main() {
  const startTime = Date.now();
  let slug = explicitSlug;

  // -------------------------------------------------------------
  // STAGE 1 & 2: DUAL-TRACK PRODUCTION (LIVE IPO OR COMPETITOR SPY)
  // -------------------------------------------------------------
  if (!slug) {
    if (typeArg === "ipo") {
      console.log("📈 [Stage 1/7] Running Real-Time Indian IPO Scraper & Freshness Filter...");
      const { pickTopTrendingIpo } = await import("./market-scraper.mjs");
      const { conductIpoResearch } = await import("./ipo-researcher.mjs");

      const topIpo = await pickTopTrendingIpo();
      console.log(`\n🎯 Selected Top Fresh Market IPO: "${topIpo.company}" (${topIpo.type})`);
      console.log(`   GMP: +${topIpo.gmpPercent}% | Subscription: ${topIpo.subMultiple}x | Status: ${topIpo.status}`);

      console.log("🤖 [Stage 2/7] Conducting Fundamental Valuation & Strategy Research...");
      const ipoReel = await conductIpoResearch(topIpo);
      slug = ipoReel.meta.slug || `${topIpo.company.toLowerCase().replace(/[^a-z0-9]+/g, "-")}-ipo`;

      const targetDir = path.join(rootDir, "reels", slug);
      fs.mkdirSync(targetDir, { recursive: true });
      fs.writeFileSync(path.join(targetDir, "reel.json"), JSON.stringify(ipoReel, null, 2), "utf-8");

      if (fs.existsSync(historyPath)) {
        const history = JSON.parse(fs.readFileSync(historyPath, "utf-8"));
        history.processedReels.push({
          channel: "live-market-ipo",
          shortcode: `ipo-${Date.now()}`,
          url: "https://www.investorgain.com/report/live-ipo-gmp/331/",
          originalTopic: `${topIpo.company} IPO Analysis`,
          ourSlug: slug,
          processedAt: new Date().toISOString(),
          status: "READY_TO_RENDER",
        });
        fs.writeFileSync(historyPath, JSON.stringify(history, null, 2));
      }
    } else {
      console.log("🔍 [Stage 1/7] Ingesting Concept & Running Deep Technical Research...");
      const spyArgs = [];
      if (explicitTopic) spyArgs.push(`--topic=${explicitTopic}`);
      if (explicitUrl) spyArgs.push(`--url=${explicitUrl}`);

      const spyScript = path.join(rootDir, "scripts", "spy-competitors.mjs");
      const spyRes = spawnSync("node", [spyScript, ...spyArgs], {
        stdio: "inherit",
        cwd: rootDir,
      });

      if (spyRes.status !== 0) {
        console.error("❌ Concept ingestion / research failed.");
        process.exit(1);
      }

      if (!fs.existsSync(historyPath)) {
        console.error("❌ History file not found.");
        process.exit(1);
      }

      const history = JSON.parse(fs.readFileSync(historyPath, "utf-8"));
      const lastReel = history.processedReels[history.processedReels.length - 1];
      if (!lastReel || !lastReel.ourSlug) {
        console.error("❌ No active reel slug generated by spy script.");
        process.exit(1);
      }
      slug = lastReel.ourSlug;
    }
  }

  console.log(`\n🎯 Active Reel Target: "${slug}"`);

  // Verify reel.json exists
  const reelJsonPath = path.join(rootDir, "reels", slug, "reel.json");
  if (!fs.existsSync(reelJsonPath)) {
    console.error(`❌ reel.json not found at: ${reelJsonPath}`);
    process.exit(1);
  }

  // -------------------------------------------------------------
  // STAGE 4: STUDIO VOICE SYNTHESIS & BROADCAST MASTERING
  // -------------------------------------------------------------
  console.log("\n🎙️ [Stage 4/7] Synthesizing Studio Voiceover (Sarvam AI Shubh + Mastering Chain)...");
  try {
    execSync(`node scripts/generate-voice.mjs "${slug}" --force --voice=${voiceArg}`, {
      stdio: "inherit",
      cwd: rootDir,
    });
  } catch (voiceErr) {
    console.error("❌ Voice synthesis failed:", voiceErr.message);
    process.exit(1);
  }

  // Check generated duration
  const updatedReel = JSON.parse(fs.readFileSync(reelJsonPath, "utf-8"));
  const durationSec = updatedReel.meta?.durationSec || 0;
  console.log(`⏱️ Verified Voiceover Runtime: ${durationSec}s`);
  if (durationSec < 26) {
    console.warn(`⚠️ Warning: Reel duration is ${durationSec}s. Target is 30-35s for high retention.`);
  }

  // -------------------------------------------------------------
  // STAGE 5: FRAME-BY-FRAME VISUAL QUALITY CONTROL
  // -------------------------------------------------------------
  console.log("\n👁️ [Stage 5/7] Executing Automated Visual QC (Safe Zones & Diagrams)...");
  try {
    execSync(`node scripts/visual-qc.mjs "${slug}"`, {
      stdio: "inherit",
      cwd: rootDir,
    });
  } catch (qcErr) {
    console.error("❌ Visual QC failed:", qcErr.message);
    process.exit(1);
  }

  // -------------------------------------------------------------
  // STAGE 6: REMOTION HIGH-BITRATE VIDEO RENDER
  // -------------------------------------------------------------
  console.log("\n🎥 [Stage 6/7] Rendering High-Definition 1080x1920 9:16 Reel & High-CTR Cover...");
  try {
    execSync(`npm run render:reel -- "${slug}"`, {
      stdio: "inherit",
      cwd: rootDir,
    });
  } catch (renderErr) {
    console.error("❌ Remotion render failed:", renderErr.message);
    process.exit(1);
  }

  // Update history status
  if (fs.existsSync(historyPath)) {
    const history = JSON.parse(fs.readFileSync(historyPath, "utf-8"));
    const entry = history.processedReels.find((r) => r.ourSlug === slug);
    if (entry) {
      entry.status = "RENDERED";
      entry.durationSec = durationSec;
      fs.writeFileSync(historyPath, JSON.stringify(history, null, 2));
    }
  }

  // -------------------------------------------------------------
  // STAGE 7: PACKAGING & OPTIONAL INSTAGRAM PUBLISH
  // -------------------------------------------------------------
  const elapsedMin = ((Date.now() - startTime) / 60000).toFixed(1);
  console.log(`\n=======================================================`);
  console.log(`🎉 STUDIO PRODUCTION COMPLETE! (Elapsed: ${elapsedMin} minutes)`);
  console.log(`📁 Master Video:    out/${slug}.mp4`);
  console.log(`🖼️  High-CTR Cover:  out/${slug}-cover.jpg`);
  console.log(`🔍 QC Frames:       out/qc-${slug}/`);
  console.log(`📊 Duration:        ${durationSec}s (Target: 30-35s)`);
  console.log(`🎙️ Voice Talent:    ${voiceArg}`);
  console.log(`=======================================================\n`);

  if (shouldPost) {
    console.log("🚀 [Stage 7/7] Auto-Publishing Reel to Instagram (@techwith.genz)...");
    try {
      execSync(`npm run post:reel:browser -- "${slug}"`, {
        stdio: "inherit",
        cwd: rootDir,
      });
      if (fs.existsSync(historyPath)) {
        const history = JSON.parse(fs.readFileSync(historyPath, "utf-8"));
        const entry = history.processedReels.find((r) => r.ourSlug === slug);
        if (entry) {
          entry.status = "POSTED";
          fs.writeFileSync(historyPath, JSON.stringify(history, null, 2));
        }
      }
      console.log("✅ Reel successfully published to Instagram with 9:16 crop & AI label ON!");
    } catch (postErr) {
      console.error("❌ Instagram posting failed:", postErr.message);
    }
  } else {
    console.log("👉 To post this reel to Instagram, run:");
    console.log(`   npm run post:reel:browser -- "${slug}"`);
    console.log(`   Or run with --post flag for end-to-end automation.`);
  }
}

main().catch((err) => {
  console.error("💥 Pipeline Fatal Error:", err);
  process.exit(1);
});

